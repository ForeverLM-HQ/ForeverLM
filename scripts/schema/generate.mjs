// MARK: - Summary

const mdCell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function homeText(home) {
  if (home.rule === "library") return "`library` (always the personal Library)";
  if (home.rule === "current") return `\`current\` (the library it is written in; \`${home.privateZone}\` in the personal library)`;
  if (home.rule === "owner") return `\`owner\` (the zone of \`${home.typeField}\` \`${home.field}\`; \`${home.privateZone}\` for a private owner or a personal \`${home.roleField}\`)`;
  const parents = home.kindField
    ? Object.entries(home.parents).map(([kind, type]) => `${kind} → ${type}`).join(", ")
    : home.parent;
  const extras = [
    home.kindField && `by \`${home.kindField}\``,
    home.personalIDPrefixes?.length && `ids starting ${home.personalIDPrefixes.map((prefix) => `\`${prefix}\``).join(", ")} stay in Library`,
    home.primaryOfSpace && `the record a \`${home.primaryOfSpace}\` space was made for lives in it`,
  ].filter(Boolean).join("; ");
  return `\`parent\` (the zone of \`${home.field}\`: ${parents}${extras ? `; ${extras}` : ""})`;
}

