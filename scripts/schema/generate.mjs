// MARK: - Settings catalog

/// The catalog the hosted MCP and the web validate Setting writes against
/// (§3.5.3): every key and family with its value type, scope, range and the
/// MCP route that sets it, the preferences generation 2 moves into typed
/// records, and the synced prefixes it leaves out, which only their own
/// writers set. One line per key, so a change reads as a one-line diff.
export function renderSettingsCatalog(schema) {
  const settings = schema.settings;
  const scoped = (entry) => {
    const row = { type: entry.type, scope: asList(entry.scope ?? "account") };
    for (const key of ["values", "range", "parts", "retired", "origin"]) if (entry[key] !== undefined) row[key] = entry[key];
    row.mcp = entry.mcp ?? null;
    row.doc = entry.doc;
    return row;
  };
  const header = {
    catalog: "settings",
    schemaRevision: schema.schemaRevision,
    doc: `${GENERATED_NOTE.replace(/\n/g, " ")} ${settings.doc} A family pattern is literal text with <name> placeholders; a placeholder matches one or more characters, and parts restricts it to a list (aiTasks: aiTasks.ids). An exact key never starts with a family's, a record's or a left-out prefix, and no prefix is listed twice.`,
    valueTypes: schema.enums.SettingValueType.values,
    scopes: settings.scopes,
    aiTasks: settings.aiTasks,
  };
  const lines = ["{"];
  for (const [key, value] of Object.entries(header)) lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  const block = (name, entries, last) => {
    lines.push(`  ${JSON.stringify(name)}: {`);
    entries.forEach(([key, value], index) => lines.push(`    ${JSON.stringify(key)}: ${value}${index === entries.length - 1 ? "" : ","}`));
    lines.push(`  }${last ? "" : ","}`);
  };
  block("keys", Object.entries(settings.keys).map(([key, entry]) => [key, JSON.stringify(scoped(entry))]), false);
  block("families", Object.entries(settings.families).map(([prefix, patterns]) => [
    prefix,
    `[\n${patterns.map((entry) => `      ${JSON.stringify({ pattern: entry.pattern, ...scoped(entry) })}`).join(",\n")}\n    ]`,
  ]), false);
  block("records", Object.entries(settings.records).map(([key, value]) => {
    const entry = recordEntry(value);
    const row = { match: key.endsWith(".") ? "prefix" : "key", ...parseRecordTarget(entry.record) };
    if (entry.origin !== undefined) row.origin = entry.origin;
    return [key, JSON.stringify(row)];
  }), false);
  block("leftOut", Object.entries(settings.leftOut ?? {}).map(([prefix, entry]) => [
    prefix,
    JSON.stringify({ pattern: entry.pattern, type: entry.type, scope: asList(entry.scope ?? "account"), doc: entry.doc }),
  ]), true);
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

// MARK: - Entry points

export function generate(schema = loadSchema()) {
  validateSchema(schema);
  return {
    [OUTPUTS.ckdb]: renderCkdb(schema),
    [OUTPUTS.swift]: renderSwift(schema),
    [OUTPUTS.js]: renderJS(schema),
    [OUTPUTS.dts]: renderDTS(schema),
    [OUTPUTS.summary]: renderSummary(schema),
    [OUTPUTS.settings]: renderSettingsCatalog(schema),
  };
}

export function writeOutputs(files, root = REPO_ROOT) {
  for (const [relativePath, contents] of Object.entries(files)) {
    const target = join(root, relativePath);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outIndex = process.argv.indexOf("--out");
  const root = outIndex > 0 ? resolve(process.argv[outIndex + 1]) : REPO_ROOT;
  try {
    const files = generate();
    writeOutputs(files, root);
    for (const relativePath of Object.keys(files)) console.log(`wrote ${relativePath}`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
