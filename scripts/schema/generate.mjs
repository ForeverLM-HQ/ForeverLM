#!/usr/bin/env node
// Generates every artifact of the CloudKit schema v2 from its one source,
// schema/cloudkit-schema.json (docs/cloudkit-schema-design.md §12.1):
//
//   schema/generated/foreverlm-library.ckdb              xcrun cktool import-schema
//   ForeverLMApp/Shared/Sync/Core/SyncSchema.generated.swift   Mac and iOS codecs
//   schema/js/schema.generated.js (+ .d.ts)              website and gateway
//   schema/generated/schema-summary.md                   docs
//   schema/generated/settings-catalog.json               Setting validation (§3.5.3)
//
// Usage: node scripts/schema/generate.mjs [--out <dir>]
// With --out, the files are written under <dir> at their repo-relative paths
// (check-generated.mjs uses that to compare a fresh run with the checked-in
// copies). No dependencies: Node's standard library only.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const SCHEMA_PATH = join(REPO_ROOT, "schema/cloudkit-schema.json");

export const OUTPUTS = Object.freeze({
  ckdb: "schema/generated/foreverlm-library.ckdb",
  swift: "ForeverLMApp/Shared/Sync/Core/SyncSchema.generated.swift",
  js: "schema/js/schema.generated.js",
  dts: "schema/js/schema.generated.d.ts",
  summary: "schema/generated/schema-summary.md",
  settings: "schema/generated/settings-catalog.json",
});

const GENERATED_NOTE =
  "Generated by scripts/schema/generate.mjs from schema/cloudkit-schema.json. Do not edit:\n" +
  "change the JSON and run `node scripts/schema/generate.mjs` (docs/cloudkit-schema-design.md §12.1).";

export function loadSchema(path = SCHEMA_PATH) {
  return JSON.parse(readFileSync(path, "utf8"));
}

// MARK: - Validation

const REQUIREMENT_WORDS = new Set(["space", "personal"]);
const ID_DETERMINISM = new Set(["yes", "partly", "no"]);
const TYPE_KEYS = new Set([
  "section", "doc", "prefix", "fixedRecordName", "zones", "home", "zoneRule", "privateOnly", "immutable",
  "singleWriter", "recreateOnUnknownItem", "flipsInsteadOfDelete", "spaceRule", "id",
  "cloudKitFields", "fields", "reserved", "reservedDoc", "onServerFirstLoss",
]);
const FIELD_KEYS = new Set([
  "json", "items", "enum", "ref", "keyRef", "kind", "policy", "required", "keys", "doc",
  "privateKindsOnly", "personalSatellite", "terminalValues", "memberLocal", "spill",
]);

/// The types whose fields may be private-kinds-only (D20): a chat's and its exchanges'.
const PRIVATE_KINDS_TYPES = new Set(["Chat", "Exchange"]);

/// A scalar string field spills into a field.<name> satellite above spillStringBytes
/// unless it is an enum or marked `"spill": false` (§3.2 rule 8). A set of strings never
/// spills: its elements are keys, each under its own stamp, and the marker takes the field's.
export const spills = (field) => field.json === "string" && field.kind === "scalar" && !field.enum && field.spill !== false;

export function asList(value) {
  if (value === undefined || value === null) return [];
  return Array.isArray(value) ? value : [value];
}

/// Throws one error listing every problem, so a bad edit is fixed in one pass.
export function validateSchema(schema) {
  const problems = [];
  const fail = (message) => problems.push(message);
  const typeNames = Object.keys(schema.types ?? {});
  const zoneNames = Object.keys(schema.zones ?? {});
  const prefixes = new Map();

  if (!Number.isInteger(schema.schemaRevision) || schema.schemaRevision < 1) fail("schemaRevision must be a positive integer");
  if (!Number.isInteger(schema.envelopeVersion) || schema.envelopeVersion < 1) fail("envelopeVersion must be a positive integer");
  if (typeof schema.container !== "string" || !schema.container.startsWith("iCloud.")) fail("container must be an iCloud container id");
  for (const key of ["env", "type", "id", "rev", "saltID", "fields", "stamps"]) {
    if (!schema.envelope?.keys?.includes(key)) fail(`envelope.keys must list ${key}`);
  }
  if (typeof schema.envelope?.spillMarker !== "string") fail("envelope.spillMarker missing");
  for (const [name, value] of Object.entries(schema.limits ?? {})) {
    if (!Number.isInteger(value) || value <= 0) fail(`limits.${name} must be a positive integer`);
  }
  for (const [name, spec] of Object.entries(schema.enums ?? {})) {
    if (!Array.isArray(spec.values) || spec.values.length === 0) fail(`enum ${name} has no values`);
    else if (new Set(spec.values).size !== spec.values.length) fail(`enum ${name} repeats a value`);
  }
  for (const [name, spec] of Object.entries(schema.cloudKit?.fields ?? {})) {
    if (!["BYTES", "ASSET"].includes(spec.type)) fail(`cloudKit field ${name} has unsupported type ${spec.type}`);
  }

  for (const typeName of typeNames) {
    const type = schema.types[typeName];
    const at = `type ${typeName}`;
    if (!/^[A-Z][A-Za-z0-9]*$/.test(typeName)) fail(`${at}: record type names are UpperCamelCase letters and digits`);
    for (const key of Object.keys(type)) if (!TYPE_KEYS.has(key)) fail(`${at}: unknown key ${key}`);
    if (type.prefix === null) {
      if (typeof type.fixedRecordName !== "string") fail(`${at}: a type without a prefix needs fixedRecordName`);
    } else if (typeof type.prefix !== "string" || !/^[a-z]{2,3}$/.test(type.prefix)) {
      fail(`${at}: prefix must be 2–3 lowercase letters`);
    } else if (prefixes.has(type.prefix)) {
      fail(`${at}: prefix ${type.prefix} is already ${prefixes.get(type.prefix)}'s`);
    } else {
      prefixes.set(type.prefix, typeName);
    }
    if (!Array.isArray(type.zones) || type.zones.length === 0) fail(`${at}: zones missing`);
    for (const zone of asList(type.zones)) if (!zoneNames.includes(zone)) fail(`${at}: unknown zone ${zone}`);
    if (typeof type.privateOnly !== "boolean") fail(`${at}: privateOnly must be true or false`);
    if (type.privateOnly && type.zones?.includes("Space")) fail(`${at}: a priv-only type cannot list the Space zone`);
    if (!type.id || !Array.isArray(type.id.forms) || type.id.forms.length === 0) fail(`${at}: id.forms missing`);
    if (!ID_DETERMINISM.has(type.id?.deterministic)) fail(`${at}: id.deterministic must be yes, partly or no`);
    if (!Array.isArray(type.cloudKitFields) || type.cloudKitFields[0] !== "payload") fail(`${at}: cloudKitFields must start with payload`);
    for (const field of asList(type.cloudKitFields)) if (!schema.cloudKit?.fields?.[field]) fail(`${at}: unknown CloudKit field ${field}`);
    if (!Array.isArray(type.reserved)) fail(`${at}: reserved must be a list (empty when nothing is retired)`);
    const fields = type.fields ?? {};
    if (Object.keys(fields).length === 0) fail(`${at}: no payload fields`);
    for (const key of asList(type.reserved)) if (fields[key]) fail(`${at}: reserved key ${key} is also a field`);
    if (type.spaceRule) {
      if (!type.zones.includes("Space")) fail(`${at}: spaceRule on a type that never lives in a space`);
      const ruled = fields[type.spaceRule.field];
      if (!ruled) fail(`${at}: spaceRule names unknown field ${type.spaceRule.field}`);
      else for (const value of type.spaceRule.allowed ?? []) {
        if (!schema.enums[ruled.enum]?.values.includes(value)) fail(`${at}: spaceRule value ${value} is not in ${ruled.enum}`);
      }
    }
    for (const [fieldName, field] of Object.entries(fields)) {
      const fat = `${at}.${fieldName}`;
      if (!/^[a-z][A-Za-z0-9]*$/.test(fieldName)) fail(`${fat}: field names are lowerCamelCase`);
      for (const key of Object.keys(field)) if (!FIELD_KEYS.has(key)) fail(`${fat}: unknown key ${key}`);
      if (!schema.jsonTypes?.[field.json]) fail(`${fat}: unknown json type ${field.json}`);
      if (field.json === "array" && !schema.jsonTypes?.[field.items]) fail(`${fat}: arrays name their items type`);
      if (!schema.fieldKinds?.[field.kind]) fail(`${fat}: unknown kind ${field.kind}`);
      if (!schema.policies?.[field.policy]) fail(`${fat}: unknown policy ${field.policy}`);
      if (field.kind === "set" && field.policy !== "L") fail(`${fat}: sets merge per element by last writer (policy L)`);
      if (field.policy === "T" && field.json !== "FileRef") fail(`${fat}: a T field is a pointer to a body satellite (FileRef)`);
      if ((field.policy === "X" || field.policy === "N") && field.kind !== "scalar") fail(`${fat}: X and N apply to scalar values`);
      const required = field.required;
      const requiredOK = typeof required === "boolean" || REQUIREMENT_WORDS.has(required) ||
        (required && typeof required === "object" && fields[required.field] && Array.isArray(required.in));
      if (!requiredOK) fail(`${fat}: required must be true, false, "space", "personal" or {field, in}`);
      if (required === "space" && !type.zones.includes("Space")) fail(`${fat}: required in a space, but the type never lives in one`);
      if (field.enum !== undefined && !schema.enums?.[field.enum]) fail(`${fat}: unknown enum ${field.enum}`);
      for (const ref of [...asList(field.ref), ...asList(field.keyRef)]) {
        if (!typeNames.includes(ref)) fail(`${fat}: ref names unknown type ${ref}`);
      }
      if (field.keyRef !== undefined && field.kind !== "map") fail(`${fat}: keyRef applies to maps`);
      if (field.privateKindsOnly !== undefined && field.privateKindsOnly !== true) fail(`${fat}: privateKindsOnly is true or absent`);
      if (field.privateKindsOnly && !PRIVATE_KINDS_TYPES.has(typeName)) fail(`${fat}: privateKindsOnly applies only to Chat and Exchange fields (D20)`);
      if (field.memberLocal !== undefined && field.memberLocal !== true) fail(`${fat}: memberLocal is true or absent`);
      if (field.memberLocal && !type.privateOnly) fail(`${fat}: a member-local field may only sit on a priv-only type (D18)`);
      if (field.spill !== undefined && (field.spill !== false || field.json !== "string" || field.enum)) {
        fail(`${fat}: "spill": false applies only to a plain string field`);
      }
      if (field.terminalValues !== undefined && (field.kind !== "scalar" || field.policy !== "L")) {
        fail(`${fat}: terminal values apply to a scalar last-writer field`);
      }
      for (const value of asList(field.terminalValues)) {
        if (!schema.enums?.[field.enum]?.values.includes(value)) fail(`${fat}: terminal value ${value} is not in ${field.enum}`);
      }
      if (typeof field.doc !== "string") fail(`${fat}: doc must be a string (may be empty)`);
    }
    for (const [fieldName, hook] of Object.entries(type.onServerFirstLoss ?? {})) {
      if (fields[fieldName]?.policy !== "S") fail(`${at}: onServerFirstLoss names ${fieldName}, which is not an S field`);
      if (typeof hook !== "string" || !/^[a-z][A-Za-z0-9]*$/.test(hook)) fail(`${at}: onServerFirstLoss hooks are lowerCamelCase names`);
    }
    if (type.immutable && Object.values(fields).some((field) => field.policy !== "S")) {
      fail(`${at}: an immutable type has only S fields`);
    }
    if (type.singleWriter && !type.id?.forms?.some((form) => form.includes("deviceID")) && !fields.deviceID) {
      fail(`${at}: a single-writer type names its writer (deviceID in the id or a deviceID field)`);
    }
    validateHome(schema, typeName, type, fail);
  }
  validateSettings(schema, fail);
  if (problems.length > 0) {
    throw new Error(`schema/cloudkit-schema.json has ${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
  }
}

const HOME_KEYS = {
  library: ["rule"],
  current: ["rule", "privateZone"],
  parent: ["rule", "field", "parent", "kindField", "parents", "personalIDPrefixes", "primaryOfSpace"],
  owner: ["rule", "field", "typeField", "roleField", "privateZone"],
};

/// `home` says where a type's records live (§4.4) for `ZonePlacement` in Swift and JS.
function validateHome(schema, typeName, type, fail) {
  const at = `type ${typeName}.home`;
  const home = type.home;
  const fields = type.fields ?? {};
  if (!home || typeof home !== "object" || !HOME_KEYS[home.rule]) {
    fail(`${at}: rule must be one of ${Object.keys(HOME_KEYS).join(", ")}`);
    return;
  }
  if (!schema.homeRules?.[home.rule]) fail(`${at}: homeRules does not document ${home.rule}`);
  for (const key of Object.keys(home)) if (!HOME_KEYS[home.rule].includes(key)) fail(`${at}: unknown key ${key} for rule ${home.rule}`);
  if (type.privateOnly !== (home.rule === "library")) fail(`${at}: priv-only types, and only they, live in library`);
  if (home.rule === "library" && (type.zones?.length !== 1 || type.zones[0] !== "Library")) fail(`${at}: a library type lists only the Library zone`);
  if ("privateZone" in home && !type.zones?.includes(home.privateZone)) fail(`${at}: privateZone ${home.privateZone} is not one of the type's zones`);
  if (home.privateZone === "Space") fail(`${at}: privateZone names a zone of the private library, never Space`);
  if ((home.rule === "current" || home.rule === "parent") && !type.zones?.includes("Space")) fail(`${at}: rule ${home.rule} is for a type that also lives in spaces`);
  if (home.rule === "parent") {
    const field = fields[home.field];
    if (!field) {
      fail(`${at}: field ${home.field} is not a field of the type`);
      return;
    }
    const refs = asList(field.ref);
    if (home.kindField) {
      const kinds = schema.enums?.[fields[home.kindField]?.enum]?.values;
      if (!kinds) fail(`${at}: kindField ${home.kindField} is not an enum field`);
      else if (JSON.stringify(Object.keys(home.parents ?? {}).sort()) !== JSON.stringify([...kinds].sort())) fail(`${at}: parents must name a type for every value of ${fields[home.kindField].enum}`);
      for (const parent of Object.values(home.parents ?? {})) if (!refs.includes(parent)) fail(`${at}: parent ${parent} is not a ref of ${home.field}`);
      if ("parent" in home) fail(`${at}: a kindField home names its types in parents, not parent`);
    } else if (!refs.includes(home.parent) || refs.length !== 1) {
      fail(`${at}: parent must be the one type ${home.field} refers to`);
    }
    for (const prefix of asList(home.personalIDPrefixes)) if (typeof prefix !== "string" || !prefix) fail(`${at}: personalIDPrefixes are non-empty strings`);
    if (home.primaryOfSpace !== undefined && !schema.enums.ZoneKind.values.includes(home.primaryOfSpace)) fail(`${at}: primaryOfSpace must be a ZoneKind`);
  }
  if (home.rule === "owner") {
    for (const key of ["field", "typeField", "roleField"]) if (!fields[home[key]]) fail(`${at}: ${key} ${home[key]} is not a field of the type`);
  }
}

const SETTING_KEYS = new Set(["type", "values", "range", "scope", "origin", "retired", "mcp", "doc"]);
const PATTERN_KEYS = new Set(["pattern", "parts", ...SETTING_KEYS]);
const MCP_KEYS = new Set(["tool", "setting", "target", "argument", "derived"]);
const RECORD_KEYS = new Set(["record", "origin"]);
const LEFT_OUT_KEYS = new Set(["pattern", "type", "scope", "doc"]);

/// A `settings.records` entry is the target text, or {record, origin: "spec"} for a
/// preference the spec maps before every generation-1 build writes it.
export const recordEntry = (entry) => (typeof entry === "string" ? { record: entry } : entry ?? {});

/// "Type", "Type.field", "Type.field.key" or "Mark(kind)": the typed record a
/// generation-1 preference moves into under generation 2 (§10).
export function parseRecordTarget(text) {
  const mark = /^Mark\(([A-Za-z]+)\)$/.exec(text);
  if (mark) return { record: "Mark", markKind: mark[1] };
  const [record, field, key, ...rest] = String(text).split(".");
  if (rest.length) return null;
  const target = { record };
  if (field) target.field = field;
  if (key) target.key = key;
  return target;
}

/// The placeholders of a family pattern, in order: aiTask.<task>.prompt → ["task"].
export const patternParts = (pattern) => [...pattern.matchAll(/<([A-Za-z]+)>/g)].map((match) => match[1]);

function validateSettings(schema, fail) {
  const settings = schema.settings;
  if (!settings) {
    fail("settings missing (§3.5.3)");
    return;
  }
  const valueTypes = schema.enums?.SettingValueType?.values ?? [];
  const scopes = Object.keys(settings.scopes ?? {});
  for (const [scope, zone] of Object.entries(settings.scopes ?? {})) {
    if (!schema.zones?.[zone]) fail(`settings.scopes.${scope} names unknown zone ${zone}`);
  }
  const taskIDs = settings.aiTasks?.ids ?? [];
  if (!Number.isInteger(settings.aiTasks?.version) || settings.aiTasks.version < 1) fail("settings.aiTasks.version must be a positive integer");
  if (taskIDs.length === 0 || new Set(taskIDs).size !== taskIDs.length) fail("settings.aiTasks.ids must be a non-empty list without repeats");
  const recordPrefixes = Object.keys(settings.records ?? {}).filter((key) => key.endsWith("."));
  const leftOutPrefixes = Object.keys(settings.leftOut ?? {});
  const prefixes = [...Object.keys(settings.families ?? {}), ...recordPrefixes, ...leftOutPrefixes];
  if (new Set(prefixes).size !== prefixes.length) fail("settings: a prefix is listed twice across families, records and leftOut");
  const checkEntry = (at, entry, allowed) => {
    for (const key of Object.keys(entry)) if (!allowed.has(key)) fail(`${at}: unknown key ${key}`);
    if (!valueTypes.includes(entry.type)) fail(`${at}: type must be one of SettingValueType (${valueTypes.join(", ")})`);
    for (const scope of asList(entry.scope)) if (!scopes.includes(scope)) fail(`${at}: unknown scope ${scope}`);
    if (entry.values !== undefined && (entry.type !== "string" || !Array.isArray(entry.values) || entry.values.length === 0)) {
      fail(`${at}: values lists a string setting's allowed values`);
    }
    if (entry.range !== undefined) {
      const { min, max, step, ...rest } = entry.range;
      if (!["int", "double"].includes(entry.type) || typeof min !== "number" || typeof max !== "number" || min > max ||
          (step !== undefined && !(step > 0)) || Object.keys(rest).length) {
        fail(`${at}: range is {min, max, step?} on an int or double setting`);
      }
    }
    if (entry.origin !== undefined && entry.origin !== "spec") fail(`${at}: origin is "spec" or absent`);
    if (entry.retired !== undefined && entry.retired !== true) fail(`${at}: retired is true or absent`);
    if (entry.retired && entry.mcp) fail(`${at}: a retired key is never written, so no tool sets it`);
    if (entry.mcp !== undefined) {
      const mcp = entry.mcp;
      for (const key of Object.keys(mcp ?? {})) if (!MCP_KEYS.has(key)) fail(`${at}: unknown mcp key ${key}`);
      if (typeof mcp?.tool !== "string" || !/^[a-z][a-z_]*$/.test(mcp.tool)) fail(`${at}: mcp.tool names an MCP tool`);
      if ((mcp?.tool === "set_app_setting") !== (typeof mcp?.setting === "string")) fail(`${at}: mcp.setting goes with set_app_setting, and only there`);
      if (mcp?.derived !== undefined && mcp.derived !== true) fail(`${at}: mcp.derived is true or absent`);
    }
    if (typeof entry.doc !== "string" || entry.doc.length === 0) fail(`${at}: doc must say what the key holds`);
  };
  for (const [key, entry] of Object.entries(settings.keys ?? {})) {
    const at = `settings.keys.${key}`;
    checkEntry(at, entry, SETTING_KEYS);
    if (settings.records?.[key]) fail(`${at}: also listed in settings.records`);
    for (const prefix of prefixes) if (key.startsWith(prefix)) fail(`${at}: starts with the prefix ${prefix}`);
  }
  for (const [prefix, patterns] of Object.entries(settings.families ?? {})) {
    if (!prefix.endsWith(".")) fail(`settings.families.${prefix}: a prefix ends with "."`);
    if (!Array.isArray(patterns) || patterns.length === 0) fail(`settings.families.${prefix}: lists its patterns`);
    for (const entry of asList(patterns)) {
      const at = `settings.families.${prefix} ${entry.pattern}`;
      checkEntry(at, entry, PATTERN_KEYS);
      if (typeof entry.pattern !== "string" || !entry.pattern.startsWith(prefix)) fail(`${at}: the pattern starts with its prefix`);
      const parts = patternParts(entry.pattern ?? "");
      for (const [name, values] of Object.entries(entry.parts ?? {})) {
        if (!parts.includes(name)) fail(`${at}: parts names ${name}, which the pattern lacks`);
        if (values !== "aiTasks" && (!Array.isArray(values) || values.length === 0)) fail(`${at}: parts.${name} is "aiTasks" or a list`);
      }
    }
  }
  for (const [key, value] of Object.entries(settings.records ?? {})) {
    const at = `settings.records.${key}`;
    const entry = recordEntry(value);
    if (typeof value !== "string") {
      for (const name of Object.keys(entry)) if (!RECORD_KEYS.has(name)) fail(`${at}: unknown key ${name}`);
      if (entry.origin !== "spec") fail(`${at}: an entry written as an object carries origin "spec"; write the target alone otherwise`);
    }
    const text = entry.record;
    const target = typeof text === "string" ? parseRecordTarget(text) : null;
    const type = target && schema.types[target.record];
    if (!type) {
      fail(`${at}: ${text} names no record type`);
      continue;
    }
    if (target.markKind && !schema.enums.MarkKind.values.includes(target.markKind)) fail(`${at}: ${target.markKind} is not a MarkKind`);
    if (target.field && !type.fields[target.field]) fail(`${at}: ${target.record} has no field ${target.field}`);
    if (target.key && type.fields[target.field]?.kind !== "map") fail(`${at}: ${target.record}.${target.field} is not a map`);
  }
  // Synced prefixes that stay Settings but stay out of the catalog: only their own writers set
  // them, never set_app_setting (§3.5.3).
  for (const [prefix, entry] of Object.entries(settings.leftOut ?? {})) {
    const at = `settings.leftOut.${prefix}`;
    if (!prefix.endsWith(".")) fail(`${at}: a prefix ends with "."`);
    for (const name of Object.keys(entry ?? {})) if (!LEFT_OUT_KEYS.has(name)) fail(`${at}: unknown key ${name}`);
    if (typeof entry?.pattern !== "string" || !entry.pattern.startsWith(prefix)) fail(`${at}: the pattern starts with its prefix`);
    if (!valueTypes.includes(entry?.type)) fail(`${at}: type must be one of SettingValueType (${valueTypes.join(", ")})`);
    for (const scope of asList(entry?.scope)) if (!scopes.includes(scope)) fail(`${at}: unknown scope ${scope}`);
    if (typeof entry?.doc !== "string" || entry.doc.length === 0) fail(`${at}: doc must say what the key holds and who writes it`);
  }
}

// MARK: - Shared helpers

const sortedTypeNames = (schema) => Object.keys(schema.types).sort();
const camel = (name) => name[0].toLowerCase() + name.slice(1);

function requirementText(required) {
  if (required === true) return "✓";
  if (required === false) return "";
  if (required === "space") return "spaces";
  if (required === "personal") return "personal root";
  return `${required.field} ∈ {${required.in.join(", ")}}`;
}

// MARK: - .ckdb

export function renderCkdb(schema) {
  const ck = schema.cloudKit;
  const blocks = [];
  const blockFor = (name, appFields, recordIDQueryable, grants) => {
    const rows = ck.systemFields.map((field) => ({
      name: `"${field.name}"`,
      type: field.name === "___recordID" && recordIDQueryable ? `${field.type} QUERYABLE` : field.type,
    }));
    for (const field of [...appFields].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
      rows.push({ name: /^[A-Za-z][A-Za-z0-9_]*$/.test(field.name) ? field.name : `"${field.name}"`, type: field.type });
    }
    const width = Math.max(...rows.map((row) => row.name.length)) + 1;
    const lines = rows.map((row) => `        ${row.name.padEnd(width)}${row.type},`);
    grants.forEach((grant, index) => lines.push(`        ${grant}${index === grants.length - 1 ? "" : ","}`));
    const quotedName = /^[A-Za-z][A-Za-z0-9_]*$/.test(name) ? name : `"${name}"`;
    return `    RECORD TYPE ${quotedName} (\n${lines.join("\n")}\n    );`;
  };
  const names = [...sortedTypeNames(schema), ...Object.keys(ck.systemTypes)].sort();
  for (const name of names) {
    const system = ck.systemTypes[name];
    if (system) {
      blocks.push(blockFor(name, system.fields, system.recordIDQueryable, system.grants));
      continue;
    }
    const type = schema.types[name];
    const appFields = type.cloudKitFields.map((field) => {
      const spec = ck.fields[field];
      return { name: field, type: spec.encrypted ? `ENCRYPTED ${spec.type}` : spec.type };
    });
    blocks.push(blockFor(name, appFields, ck.recordIDQueryable, ck.grants));
  }
  return `DEFINE SCHEMA\n\n${blocks.join("\n\n")}\n`;
}

// MARK: - Swift

function swiftString(value) {
  return `"${String(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")}"`;
}

const swiftStringArray = (values) => `[${values.map(swiftString).join(", ")}]`;

function swiftRequirement(required) {
  if (required === true) return ".always";
  if (required === false) return ".optional";
  if (required === "space") return ".inSpace";
  if (required === "personal") return ".inPersonalLibrary";
  return `.whenField(${swiftString(required.field)}, in: ${swiftStringArray(required.in)})`;
}

const SWIFT_POLICY = { L: ".lastWriter", S: ".serverFirst", X: ".maximum", N: ".minimum", T: ".textBody" };

function swiftNumber(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "_");
}

function swiftHome(home) {
  let rule;
  if (home.rule === "library") rule = ".library";
  else if (home.rule === "current") rule = `.current(privateZone: .${camel(home.privateZone)})`;
  else if (home.rule === "owner") {
    rule = `.owner(field: ${swiftString(home.field)}, typeField: ${swiftString(home.typeField)}, ` +
      `roleField: ${swiftString(home.roleField)}, privateZone: .${camel(home.privateZone)})`;
  } else if (home.kindField) {
    const parents = Object.entries(home.parents).map(([kind, type]) => `${swiftString(kind)}: .${camel(type)}`);
    rule = `.container(field: ${swiftString(home.field)}, kindField: ${swiftString(home.kindField)}, parents: [${parents.join(", ")}])`;
  } else {
    rule = `.parent(field: ${swiftString(home.field)}, parent: .${camel(home.parent)})`;
  }
  const args = [rule];
  if (home.personalIDPrefixes?.length) args.push(`personalIDPrefixes: ${swiftStringArray(home.personalIDPrefixes)}`);
  if (home.primaryOfSpace) args.push(`primaryOfSpace: ${swiftString(home.primaryOfSpace)}`);
  return `SyncHome(${args.join(", ")})`;
}

