  out.push("  if (value && typeof value === \"object\" && !Object.isFrozen(value)) {");
  out.push("    Object.freeze(value);");
  out.push("    for (const child of Object.values(value)) deepFreeze(child);");
  out.push("  }");
  out.push("  return value;");
  out.push("}");
  out.push("");
  out.push(`export const SCHEMA_REVISION = ${schema.schemaRevision};`);
